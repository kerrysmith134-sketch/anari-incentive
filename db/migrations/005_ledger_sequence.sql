-- ---------------------------------------------------------------------------
-- Ledger ordering
--
-- The per-tenant hash chain is built in insertion order. Two entries created
-- in the same transaction share created_at, so ordering by (created_at, id)
-- can disagree with the chain. A monotonic sequence makes verification stable.
-- ---------------------------------------------------------------------------

ALTER TABLE amount_ledger
  ADD COLUMN ledger_seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX idx_ledger_tenant_sequence
  ON amount_ledger(tenant_id, ledger_seq);
