/**
 * Declared column contract for core (money-path and audit) tables.
 *
 * This registry is the single source for the entity columns that migrations
 * must provide. `tests/ddl-contract.test.ts` parses `db/migrations/*.sql` and
 * compares the result with this list; `npm run contracts:entities` regenerates
 * `docs/generated/entity-contracts.json`. Add a column here first, then add
 * the migration, otherwise the contract test fails.
 *
 * Migrations stay hand-written: constraints, triggers, grants and data
 * migrations are not expressible as column metadata (see ADR-009).
 */

